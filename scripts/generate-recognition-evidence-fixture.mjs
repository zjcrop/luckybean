import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const readSource=p=>Buffer.from(fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n'),'utf8');
const sourcePath='public/fallback-codebook.json';
const bytes=readSource(path.join(root,sourcePath));
const book=JSON.parse(bytes);
const signals={identity:[],process:[]};
const codes=new Map();
for(const table of ['countries','regions','entities','varieties','processes']) {
  const kind=table==='processes'?'process':'identity';
  const start=table==='regions'?2:table==='entities'?3:1;
  for(const row of book[table]||[]) {
    codes.set(row[0],kind);
    for(const value of row.slice(start)) if(typeof value==='string'&&!['active','candidate','deprecated','estate_or_farm','washing_station'].includes(value)) {
      signals[kind].push(...value.split(/[\\/、,，;；|]/).map(v=>v.normalize('NFKC').trim()).filter(v=>v.length>=2));
    }
  }
}
for(const [code,alias] of book.aliases||[]) if(codes.has(code)&&typeof alias==='string') signals[codes.get(code)].push(alias);
const sources=[{path:sourcePath,owner:'BrewIon',url:'https://github.com/zjcrop/BrewIon/blob/main/coffee-qr-codebook/coffee_qr_codebook_v6.json',version:String(book.version),sha256:createHash('sha256').update(bytes).digest('hex')}];
for(const [file,kind] of [['origin.seed.json','identity'],['variety.seed.json','identity'],['processing.seed.json','process']]) {
  const p='contracts/dictionaries/'+file, b=readSource(path.join(root,p));
  sources.push({path:p,owner:'Foundation dictionary fixture',sha256:createHash('sha256').update(b).digest('hex')});
  for(const item of JSON.parse(b).items||[]) signals[kind].push(...['name_zh','name_en','name_ja','name_ko'].map(k=>item[k]),...(item.aliases||[]),...(item.ocr_aliases||[]));
}
const knowledgePath='contracts/dictionaries/knowledge-evidence-aliases.seed.json';
const knowledgeBytes=readSource(path.join(root,knowledgePath));
const knowledge=JSON.parse(knowledgeBytes);
sources.push({path:knowledgePath,owner:'BrewIon Coffee Knowledge',version:knowledge.version,sha256:createHash('sha256').update(knowledgeBytes).digest('hex'),origin:knowledge.origin});
for(const record of [...(knowledge.localizedNames||[]),...(knowledge.localizedAliases||[])]) {
  const kind=codes.get(record.targetCode), alias=record.alias||record.name;
  const accepted=['official','canonical','market_verified','common'].includes(record.nameType)||(['ai_translated','ai_transliterated'].includes(record.nameType)&&String(record.reviewStatus||'').startsWith('pending'));
  if(kind&&alias&&accepted&&Number(record.confidence)>=0.65)signals[kind].push(alias);
}
const lexiconPath='contracts/dictionaries/brewion-label-lexicon.seed.json';
const lexiconBytes=readSource(path.join(root,lexiconPath)),lexicon=JSON.parse(lexiconBytes);
sources.push({path:lexiconPath,owner:'BrewIon label lexicon',version:lexicon.version,url:'https://github.com/zjcrop/BrewIon/blob/main/coffee-qr-codebook/coffee_label_lexicon_v1.json',sha256:createHash('sha256').update(lexiconBytes).digest('hex')});
for(const [field,kind] of [['species','identity'],['process','process']])for(const aliases of Object.values(lexicon.valueAliases[field]||{}))signals[kind].push(...aliases);
for(const kind of Object.keys(signals)) signals[kind]=[...new Set(signals[kind].filter(v=>typeof v==='string'&&v.trim().length>=2).map(v=>v.normalize('NFKC').trim()))].sort();
const fixture={contract:'recognition-evidence-signals/1.0',authority:'segmentation-only',requiresUserConfirmation:true,sources,signals};
const output='// Generated by scripts/generate-recognition-evidence-fixture.mjs; do not edit aliases here.\nexport default '+JSON.stringify(fixture,null,2)+';\n';
const target=path.join(root,'src/domain/recognition/recognition-evidence-fixture.js');
if(process.argv.includes('--check')) {if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('Recognition evidence fixture is stale');console.log('Recognition evidence fixture matches pinned dictionary sources');}
else fs.writeFileSync(target,output);
