import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = path => fs.readFileSync(path, 'utf8');
const pkg = JSON.parse(read('package.json'));
const index = read('index.html');
const sw = read('sw.js');
const qr = read('src/qr.js');
const qrUi = read('src/qr-ui-controller.js');
const flavorGuide = read('src/ui/flavor-guide-controller.js');
const enrichment = read('src/services/bean-enrichment-service.js');
const gear = read('src/ui/gear-controller.js');
const components = read('src/ui/app-components.css');
const androidBuild = read('android/app/build.gradle');

const revisionMatch = index.match(/release-revision" content="([^"]+)"/);
assert.ok(revisionMatch, 'release revision missing from index');
const releaseRevision = revisionMatch[1];
assert.match(releaseRevision, /^1\.23E-main-sync\.\d+$/);
const syncNumber = releaseRevision.match(/main-sync\.(\d+)$/)?.[1];
assert.ok(syncNumber, 'release sync number missing');
const versionCodeMatch = androidBuild.match(/versionCode\s+(\d+)/);
assert.ok(versionCodeMatch, 'Android versionCode missing');
assert.ok(Number(versionCodeMatch[1]) > 102314, `upgrade versionCode must exceed 102314, got ${versionCodeMatch[1]}`);

assert.equal(pkg.dependencies?.jsqr, '1.4.0');
assert.match(pkg.scripts?.postinstall || '', /prepare-vendor\.mjs/);
assert.ok(fs.existsSync('public/vendor/jsqr/jsQR.js'), 'npm postinstall must vendor jsQR before tests');
assert.match(qr, /LOCAL_JSQR_URL/);
assert.match(qr, /public\/vendor\/jsqr\/jsQR\.js/);
assert.doesNotMatch(qr, /cdn\.jsdelivr\.net/);
assert.doesNotMatch(qr, /decodeEncryptedShareEnvelope/);
assert.match(qr, /class CameraScanner/);
assert.match(qr, /async restart\(\)/);
assert.match(qrUi, /cameraRetryBtn/);
assert.match(qrUi, /LuckyBeanQrScanner/);
assert.match(qrUi, /scanner\.restart/);
assert.match(flavorGuide, /const FLAVOR_GROUPS = \['花香','果香','茶感','香料','其他'\]/);
assert.match(enrichment, /flavorText: flavorNames\.join\(' '\)/);
assert.match(flavorGuide, /模型推荐结果/);
assert.match(flavorGuide, /data-lb-open-guide/);
assert.match(flavorGuide, /data\.settingsKey = 'about'|dataset\.settingsKey = 'about'/);
assert.match(flavorGuide, /请先在器设页面中注册或登录账户，以便同步数据到云端/);
assert.match(flavorGuide, /杯测品鉴/);
assert.match(flavorGuide, /玩家互动品鉴/);
assert.match(flavorGuide, /札记/);
assert.match(gear, /滤杯角度/);
assert.match(gear, /旁通量/);
assert.match(gear, /过滤速度/);
assert.doesNotMatch(gear, /MutationObserver/);
assert.match(components, /\.lb-open-guide/);
assert.ok(index.includes(`src/ui/gear-controller.js?v=${releaseRevision}`), 'gear controller revision must match current release');
assert.doesNotMatch(index, /interaction-repair|gear-matching-controller|gear-regression-fix|legacy-timer-guard|experience-fixes/);
assert.ok(sw.includes(`REVISION = '${releaseRevision}'`), 'service worker revision must match current release');
assert.ok(sw.includes(`main-sync-${syncNumber}`), 'service worker cache generation must match current release');
assert.doesNotMatch(sw, /interaction-repair|gear-matching-controller|gear-regression-fix-controller|legacy-timer-guard|experience-fixes-controller/);
console.log('LuckyBean 1.23E canonical QR, bean matching, gear, flavor taxonomy, user-guide and upgrade release checks passed');
