import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = path => fs.readFileSync(path, 'utf8');
const app = read('src/app.js');
const css = read('src/ui/app-components.css');
const releaseCss = read('src/release-1.24b.css');
const releaseIntegration = read('src/features/release-1.24b-integration.js');
const releaseUi = read('src/features/release-1.24b-finalize.js');
const gear = read('src/ui/gear-controller.js');
const flavorGuide = read('src/ui/flavor-guide-controller.js');
const cooling = read('src/ui/brew-cooling-controller.js');
const build = read('android/app/build.gradle');

const versionCodeMatch = build.match(/versionCode\s+(\d+)/);
assert.ok(versionCodeMatch, 'Android versionCode missing');
assert.equal(Number(versionCodeMatch[1]), 102402);
assert.match(build, /versionName '1\.24B'/);

const renderStart = app.indexOf('function renderBrew()');
const renderEnd = app.indexOf('function openCoolingDialog', renderStart);
const render = app.slice(renderStart, renderEnd);
assert.ok(renderStart > 0 && renderEnd > renderStart);
const order = ['data-brew-row="dose-ratio"','data-brew-row="filter-gear-water"','data-brew-row="actions"','data-brew-row="cooling"','data-brew-row="profile"'].map(token => render.indexOf(token));
assert.ok(order.every(value => value >= 0));
assert.deepEqual([...order].sort((a,b)=>a-b), order);
assert.doesNotMatch(render, /brewDripperMaterial/);
assert.doesNotMatch(render, /brewSegments/);
assert.match(render, /value="recommended"[^>]*>自动/);
assert.match(render, /value="recommended"[^>]*>\$\{recommendedDripper \? esc\(recommendedDripper\.name \|\| recommendedDripper\.type\) : '自动'\}/);
assert.doesNotMatch(render, />方案推荐/);
assert.doesNotMatch(render, /自动 ·/);
assert.match(render, /value="plain"[^>]*>纯水/);
assert.match(app, /brewProfileOverride: null/);
assert.match(app, /entryMode = 'normal'/);
assert.match(app, /switchPage\('brew', \{ entryMode: 'replay' \}\)/);
assert.match(app, /profileId: 'recommended', segmentMode: 'auto'/);
assert.match(app, /dripperSelectionMode: dripperSelection === 'recommended'/);
assert.match(app, /firstTemperatureC: state\.settings\.brew\.firstCoolingMode === 'custom' \? Number\(state\.settings\.brew\.firstTemperatureC\) : null/);
assert.match(app, /tailTemperatureC: state\.settings\.brew\.tailCoolingMode === 'custom' \? Number\(state\.settings\.brew\.tailTemperatureC\) : null/);
assert.doesNotMatch(app, /select\.addEventListener\('pointerdown', reopenCustom\)/);
assert.match(app, /openBrewEnvironmentDialog/);
assert.match(app, /recommendedDripperForBrew/);
assert.match(render, /data-recommended-dripper-id/);
assert.doesNotMatch(gear, /\[data-lb-brew-dripper-properties\].*remove/);
assert.match(flavorGuide, /<strong>自动<\/strong>/);
assert.match(cooling, /firstCoolingMode/);
assert.match(cooling, /tailCoolingMode/);
assert.match(css, /\.lb-brew-five-row/);
assert.match(css, /#brewDose\s*\{[^}]*font-weight:\s*800/s);
assert.match(css, /#brewRatio\s*\{[^}]*font-weight:\s*800/s);
assert.match(css, /#brewProfile\s*\{[^}]*font-weight:\s*800/s);
assert.match(releaseCss,/\.lb-auto-note/);
assert.match(releaseCss,/\.lb-auto-field/);
assert.match(releaseCss,/\.lb-compact-hidden-label/);
assert.match(releaseIntegration,/灰色框选为自动计算选项/);
assert.match(releaseUi,/data-lb-local-method-row/);
assert.match(releaseUi,/研磨|fineAnchor/);
console.log('LuckyBean 1.24B compact small-brew, automatic-field and Android upgrade contract passed');
